export type MarkedText = {
  text: string;
  generated?: boolean;
};

export type PracticeBlock =
  | {
      type: "heading";
      text: MarkedText;
      level?: 3 | 4;
    }
  | {
      type: "paragraph";
      text: MarkedText;
    }
  | {
      type: "list";
      title?: MarkedText;
      ordered?: boolean;
      items: MarkedText[];
    }
  | {
      type: "table";
      title?: MarkedText;
      headers?: MarkedText[];
      rows: MarkedText[][];
    }
  | {
      type: "image";
      src: string;
      alt: string;
      width?: number;
      height?: number;
      caption?: MarkedText;
    }
  | {
      type: "answerInstruction";
      text: MarkedText;
    }
  | {
      type: "note";
      text: MarkedText;
    };

export type PracticeOption = {
  label: string;
  text: MarkedText;
};

export type GuidedSubtask = {
  id: string;
  title?: MarkedText;
  prompt: MarkedText;
  answer: MarkedText;
  explanation?: MarkedText;
};

export type PracticePart =
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "single_choice";
      options: PracticeOption[];
      correctAnswer: string;
      explanation: MarkedText;
      distractorExplanations?: Record<string, MarkedText>;
    }
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "multi_select_exact_n";
      options: PracticeOption[];
      correctAnswers: string[];
      exactSelectionCount: number;
      explanation: MarkedText;
      optionExplanations?: Record<string, MarkedText>;
    }
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "guided_subtasks";
      subtasks: GuidedSubtask[];
      explanation?: MarkedText;
    }
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "reveal_answer";
      answer: MarkedText;
      explanation?: MarkedText;
    };

export type PracticeItem = {
  id: string;
  chapterId: number;
  sourceLabel: string;
  title: string;
  blocks: PracticeBlock[];
  parts: PracticePart[];
};


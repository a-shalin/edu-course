export function getChapter(id: number): Chapter | undefined {
  return chapters.find((chapter) => chapter.id === id);
}

export function getExcerptsByChapter(chapterId: number): LessonExcerpt[] {
  return lessonExcerpts.filter((excerpt) => excerpt.chapterId === chapterId);
}

export function getSupportingExcerptsByPracticeItem(practiceItemId: string): LessonExcerpt[] {
  return lessonExcerpts.filter((excerpt) =>
    excerpt.supportsPracticeItemIds.includes(practiceItemId)
  );
}

export function getReadyChapterCount(): number {
  return chapters.filter((chapter) => chapter.status === "ready").length;
}

import type {
  MarkedText,
  PracticeBlock,
  PracticeItem,
  PracticeOption,
  PracticePart,
} from "./practice";

type Chapter4PracticeSeed = Omit<PracticeItem, "sourceOrder" | "sourceLabel">;

const gen = (text: string): MarkedText => ({ text, generated: true });
const plain = (text: string): MarkedText => ({ text });

const heading = (text: string, level: 3 | 4 = 4): PracticeBlock => ({
  type: "heading",
  level,
  text: plain(text),
});

const paragraph = (text: string): PracticeBlock => ({
  type: "paragraph",
  text: plain(text),
});

const list = (items: string[], ordered = false, title?: string): PracticeBlock => ({
  type: "list",
  ordered,
  title: title ? plain(title) : undefined,
  items: items.map(plain),
});

const table = (rows: string[][], headers?: string[], title?: string): PracticeBlock => ({
  type: "table",
  title: title ? plain(title) : undefined,
  headers: headers?.map(plain),
  rows: rows.map((row) => row.map(plain)),
});

const image = (
  src: string,
  alt: string,
  width: number,
  height: number,
  caption?: string
): PracticeBlock => ({
  type: "image",
  src,
  alt,
  width,
  height,
  caption: caption ? gen(caption) : undefined,
});

const answerInstruction = (text: string): PracticeBlock => ({
  type: "answerInstruction",
  text: plain(text),
});

const option = (label: string, text: string, generated = false): PracticeOption => ({
  label,
  text: generated ? gen(text) : plain(text),
});

const mcq = (
  id: string,
  correctAnswer: string,
  options: PracticeOption[],
  explanation: string,
  prompt?: string,
  title?: string
): PracticePart => ({
  id,
  title: title ? gen(title) : undefined,
  prompt: prompt ? gen(prompt) : undefined,
  interaction: "single_choice",
  options,
  correctAnswer,
  explanation: gen(explanation),
});

const chooseN = (
  id: string,
  correctAnswers: string[],
  options: PracticeOption[],
  explanation: string,
  exactSelectionCount: number,
  prompt?: string,
  title?: string
): PracticePart => ({
  id,
  title: title ? gen(title) : undefined,
  prompt: prompt ? gen(prompt) : undefined,
  interaction: "multi_select_exact_n",
  options,
  correctAnswers,
  exactSelectionCount,
  explanation: gen(explanation),
});

const chooseTwo = (
  id: string,
  correctAnswers: string[],
  options: PracticeOption[],
  explanation: string,
  prompt?: string,
  title?: string
): PracticePart => chooseN(id, correctAnswers, options, explanation, 2, prompt, title);


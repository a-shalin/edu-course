export type MarkedText = {
  text: string;
  generated?: boolean;
};

export type PracticeBlock =
  | {
      type: "heading";
      text: MarkedText;
      level?: 3 | 4;
    }
  | {
      type: "paragraph";
      text: MarkedText;
    }
  | {
      type: "list";
      title?: MarkedText;
      ordered?: boolean;
      items: MarkedText[];
    }
  | {
      type: "table";
      title?: MarkedText;
      headers?: MarkedText[];
      rows: MarkedText[][];
    }
  | {
      type: "image";
      src: string;
      alt: string;
      width?: number;
      height?: number;
      caption?: MarkedText;
    }
  | {
      type: "answerInstruction";
      text: MarkedText;
    }
  | {
      type: "note";
      text: MarkedText;
    };

export type PracticeOption = {
  label: string;
  text: MarkedText;
};

export type GuidedSubtask = {
  id: string;
  title?: MarkedText;
  prompt: MarkedText;
  answer: MarkedText;
  explanation?: MarkedText;
};

export type PracticePart =
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "single_choice";
      options: PracticeOption[];
      correctAnswer: string;
      explanation: MarkedText;
      distractorExplanations?: Record<string, MarkedText>;
    }
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "multi_select_exact_n";
      options: PracticeOption[];
      correctAnswers: string[];
      exactSelectionCount: number;
      explanation: MarkedText;
      optionExplanations?: Record<string, MarkedText>;
    }
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "guided_subtasks";
      subtasks: GuidedSubtask[];
      explanation?: MarkedText;
    }
  | {
      id: string;
      title?: MarkedText;
      prompt?: MarkedText;
      interaction: "reveal_answer";
      answer: MarkedText;
      explanation?: MarkedText;
    };

export type PracticeItem = {
  id: string;
  chapterId: number;
  controlWork: number;
  variant: number;
  exerciseNumber: number;
  fragmentKey?: string;
  sourceOrder: number;
  sourceLabel: string;
  title: string;
  blocks: PracticeBlock[];
  parts: PracticePart[];
};

export function isScorablePracticePart(part: PracticePart): part is Extract<
  PracticePart,
  { interaction: "single_choice" | "multi_select_exact_n" }
> {
  return part.interaction === "single_choice" || part.interaction === "multi_select_exact_n";
}

export function isScorablePracticeItem(item: PracticeItem): boolean {
  return item.parts.some(isScorablePracticePart);
}

export function getScorablePracticeItemCount(items: PracticeItem[]): number {
  return items.filter(isScorablePracticeItem).length;
}

type PracticeSeed = Omit<PracticeItem, "sourceOrder" | "sourceLabel">;

const gen = (text: string): MarkedText => ({ text, generated: true });
const plain = (text: string): MarkedText => ({ text });

const heading = (text: string, level: 3 | 4 = 4): PracticeBlock => ({
  type: "heading",
  level,
  text: plain(text),
});

const paragraph = (text: string): PracticeBlock => ({
  type: "paragraph",
  text: plain(text),
});

const list = (items: string[], ordered = false, title?: string): PracticeBlock => ({
  type: "list",
  ordered,
  title: title ? plain(title) : undefined,
  items: items.map(plain),
});

const table = (
  rows: string[][],
  headers?: string[],
  title?: string
): PracticeBlock => ({
  type: "table",
  title: title ? plain(title) : undefined,
  headers: headers?.map(plain),
  rows: rows.map((row) => row.map(plain)),
});

const image = (
  src: string,
  alt: string,
  width: number,
  height: number,
  caption?: string
): PracticeBlock => ({
  type: "image",
  src,
  alt,
  width,
  height,
  caption: caption ? plain(caption) : undefined,
});

const answerInstruction = (text: string): PracticeBlock => ({
  type: "answerInstruction",
  text: plain(text),
});

const option = (label: string, text: string, generated = false): PracticeOption => ({
  label,
  text: generated ? gen(text) : plain(text),
});

const mcq = (
  id: string,
  correctAnswer: string,
  options: PracticeOption[],
  explanation: string,
  prompt?: string,
  title?: string
): PracticePart => ({
  id,
  title: title ? gen(title) : undefined,
  prompt: prompt ? gen(prompt) : undefined,
  interaction: "single_choice",
  options,
  correctAnswer,
  explanation: gen(explanation),
});

const chooseTwo = (
  id: string,
  correctAnswers: string[],
  options: PracticeOption[],
  explanation: string,
  prompt?: string,
  title?: string
): PracticePart => ({
  id,
  title: title ? gen(title) : undefined,
  prompt: prompt ? gen(prompt) : undefined,
  interaction: "multi_select_exact_n",
  options,
  correctAnswers,
  exactSelectionCount: 2,
  explanation: gen(explanation),
});

const sourceLabelFor = (item: PracticeSeed): string => {
  const base = `Контрольная работа № ${item.controlWork}, вариант ${item.variant}, задание ${item.exerciseNumber}`;
  return item.fragmentKey ? `${base}${item.fragmentKey}` : base;
};

